import {auditExtractedTextRuns, parseExtractedTextRuns} from '../RulesParser';
import {buildUniqueAnchor, slugifyAnchor} from '../anchor';
import {ExtractedTextRun, RulesParseMetadata} from '../types';

const metadata: RulesParseMetadata = {
  sourceUrl: 'https://example.org/rules.pdf',
  sourceSha256: 'abc123',
  generatedAt: '2026-02-14T00:00:00.000Z',
  version: '2026.02.14.1',
};

describe('rules parser', () => {
  it('reconstructs two-column reading order on a page', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 230, y: 30, text: 'R1'},
      {page: 1, x: 20, y: 20, text: 'L2'},
      {page: 1, x: 20, y: 30, text: 'L1'},
      {page: 1, x: 230, y: 20, text: 'R2'},
      {page: 1, x: 20, y: 10, text: 'L3'},
      {page: 1, x: 230, y: 10, text: 'R3'},
    ];

    const parsed = parseExtractedTextRuns(items, metadata);
    const introSection = parsed.sections[0];
    const text = introSection.blocks
      .flatMap(block => block.textRuns)
      .map(run => run.text)
      .join(' ')
      .replace(/\s+/g, ' ')
      .trim();
    expect(text).toBe('L1 L2 L3 R1 R2 R3');
  });

  it('keeps line tokens together when ordering two-column pages', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 20, y: 30, text: 'Left line has m'},
      {page: 1, x: 129, y: 30, text: 'ultiple words'},
      {page: 1, x: 300, y: 30, text: 'R1'},
      {page: 1, x: 20, y: 20, text: 'L2'},
      {page: 1, x: 300, y: 20, text: 'R2'},
    ];

    const parsed = parseExtractedTextRuns(items, metadata);
    const text = parsed.sections[0].blocks
      .flatMap(block => block.textRuns)
      .map(run => run.text)
      .join(' ')
      .replace(/\s+/g, ' ')
      .trim();

    expect(text).toContain('Left line has multiple words');
    expect(text.indexOf('Left line has multiple words')).toBeLessThan(text.indexOf('R1'));
    expect(text.indexOf('L2')).toBeLessThan(text.indexOf('R2'));
  });

  it('rejoins split words created by fragmented pdf text runs', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 20, y: 30, text: '1. Split Words', fontSize: 18},
      {page: 1, x: 20, y: 20, text: 'The Force is generated by all li'},
      {page: 1, x: 210, y: 20, text: 'ving beings and De'},
      {page: 1, x: 360, y: 20, text: 'stiny draws.'},
      {page: 1, x: 20, y: 10, text: 'A Few Maneuv'},
      {page: 1, x: 130, y: 10, text: 'ers is clarified.'},
    ];

    const parsed = parseExtractedTextRuns(items, metadata);
    const text = parsed.sections[0].blocks
      .flatMap(block => block.textRuns)
      .map(run => run.text)
      .join(' ')
      .replace(/\s+/g, ' ')
      .trim();

    expect(text).toContain('The Force is generated by all living beings and Destiny draws.');
    expect(text).toContain('A Few Maneuvers is clarified.');
  });

  it('rejoins split words that occur inside a single extracted run', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 20, y: 30, text: '1. Single Run Splits', fontSize: 18},
      {
        page: 1,
        x: 20,
        y: 20,
        text: 'A Few Maneuv ers refers to a de stiny draw and should be re adable.',
      },
    ];

    const parsed = parseExtractedTextRuns(items, metadata);
    const paragraph = parsed.sections[0].blocks
      .flatMap(block => block.textRuns)
      .map(run => run.text)
      .join(' ')
      .replace(/\s+/g, ' ')
      .trim();

    expect(paragraph).toContain(
      'A Few Maneuvers refers to a destiny draw and should be readable.',
    );
  });

  it('strips recurring footer lines and page markers from content', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 20, y: 40, text: '1. Intro', fontSize: 18},
      {page: 1, x: 20, y: 30, text: 'Real paragraph content.'},
      {page: 1, x: 20, y: 20, text: 'Not Endorsed or Sponsored by Lucasfilm Page 8'},
      {page: 1, x: 20, y: 10, text: 'Page 8'},
    ];

    const parsed = parseExtractedTextRuns(items, metadata);
    const text = parsed.sections[0].blocks
      .flatMap(block => block.textRuns)
      .map(run => run.text)
      .join(' ')
      .replace(/\s+/g, ' ')
      .trim();

    expect(text).toContain('Real paragraph content.');
    expect(text).not.toContain('Not Endorsed or Sponsored by Lucasfilm');
    expect(text).not.toContain('Page 8');
  });

  it('keeps per-block page provenance while removing Page X marker text', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 20, y: 40, text: '1. Intro', fontSize: 18},
      {page: 1, x: 20, y: 30, text: 'First page paragraph without period'},
      {page: 1, x: 20, y: 10, text: 'Page 1'},
      {page: 2, x: 20, y: 30, text: 'Second page continuation.'},
      {page: 2, x: 20, y: 10, text: 'Page 2'},
    ];

    const parsed = parseExtractedTextRuns(items, metadata);
    const paragraphs = parsed.sections[0].blocks.filter(block => block.type === 'paragraph');

    expect(paragraphs).toHaveLength(2);
    expect(paragraphs[0].pageRef).toBe(1);
    expect(paragraphs[1].pageRef).toBe(2);
    const text = paragraphs.flatMap(block => block.textRuns).map(run => run.text).join(' ');
    expect(text).not.toContain('Page 1');
    expect(text).not.toContain('Page 2');
  });

  it('merges orphaned mid-sentence paragraph fragments', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 20, y: 40, text: '1. Intro', fontSize: 18},
      {page: 1, x: 20, y: 30, text: 'during the result step of the'},
      {page: 1, x: 190, y: 20, text: 'appropriate'},
      {page: 1, x: 20, y: 10, text: 'number of cards from either one of the decks.'},
    ];

    const parsed = parseExtractedTextRuns(items, metadata);
    const paragraphs = parsed.sections[0].blocks.filter(block => block.type === 'paragraph');
    expect(paragraphs).toHaveLength(1);
    const paragraphText = paragraphs[0].textRuns.map(run => run.text).join(' ');
    expect(paragraphText).toContain(
      'during the result step of the appropriate number of cards from either one of the decks.',
    );
  });

  it('merges uppercase continuation paragraph when previous line ends with continuation cue', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 20, y: 40, text: '1. Intro', fontSize: 18},
      {
        page: 1,
        x: 20,
        y: 30,
        text: 'However, if your card is stacked at any time (unless a',
      },
      {
        page: 1,
        x: 190,
        y: 20,
        text: "Bluff cards, combat cards, and cards under his Starting Effect).",
      },
    ];

    const parsed = parseExtractedTextRuns(items, metadata);
    const paragraphs = parsed.sections[0].blocks.filter(block => block.type === 'paragraph');
    expect(paragraphs).toHaveLength(1);
    const paragraphText = paragraphs[0].textRuns.map(run => run.text).join(' ');
    expect(paragraphText).toContain('unless a Bluff cards, combat cards');
  });

  it('preserves emphasis traits from extracted runs', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 20, y: 40, text: '1. Intro', fontSize: 18},
      {page: 1, x: 20, y: 30, text: 'Bold', isBold: true},
      {page: 1, x: 70, y: 30, text: 'word'},
      {page: 1, x: 120, y: 30, text: 'italic', isItalic: true},
    ];

    const parsed = parseExtractedTextRuns(items, metadata);
    const paragraph = parsed.sections[0].blocks.find(block => block.type === 'paragraph');
    expect(paragraph).toBeTruthy();
    const runs = paragraph!.textRuns;
    expect(runs.length).toBeGreaterThanOrEqual(3);
    expect(runs[0].bold).toBe(true);
    expect(runs[1].bold).not.toBe(true);
    expect(runs[runs.length - 1].italic).toBe(true);
  });

  it('inserts space between adjacent runs when style changes on same line', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 20, y: 40, text: '1. Intro', fontSize: 18},
      {page: 1, x: 20, y: 30, text: 'Stack', isBold: true},
      {page: 1, x: 70, y: 30, text: 'One or more cards'},
    ];

    const parsed = parseExtractedTextRuns(items, metadata);
    const paragraph = parsed.sections[0].blocks.find(block => block.type === 'paragraph');
    expect(paragraph).toBeTruthy();
    const text = paragraph!.textRuns
      .map(run => run.text)
      .join('')
      .replace(/\s+/g, ' ')
      .trim();

    expect(text).toContain('Stack One or more cards');
    expect(text).not.toContain('StackOne');
  });

  it('keeps list bullets grouped with their introducing text', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 20, y: 40, text: '1. Intro', fontSize: 18},
      {page: 1, x: 20, y: 30, text: 'You may not:'},
      {page: 1, x: 38, y: 20, text: '• draw cards from Reserve Deck;'},
      {page: 1, x: 38, y: 10, text: '• search your Lost Pile.'},
    ];

    const parsed = parseExtractedTextRuns(items, metadata);
    const paragraphs = parsed.sections[0].blocks.filter(block => block.type === 'paragraph');
    expect(paragraphs).toHaveLength(1);
    const text = paragraphs[0].textRuns.map(run => run.text).join('');
    expect(text).toContain('You may not:');
    expect(text).toContain('• draw cards from Reserve Deck;');
    expect(text).toContain('• search your Lost Pile.');
  });

  it('keeps bullet lines grouped even when OCR drops the post-bullet space', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 20, y: 40, text: '1. Intro', fontSize: 18},
      {page: 1, x: 20, y: 30, text: 'You may not:'},
      {page: 1, x: 38, y: 20, text: '•draw cards from Reserve Deck;'},
      {page: 1, x: 38, y: 10, text: '•search your Lost Pile.'},
    ];

    const parsed = parseExtractedTextRuns(items, metadata);
    const paragraphs = parsed.sections[0].blocks.filter(block => block.type === 'paragraph');
    expect(paragraphs).toHaveLength(1);
    const text = paragraphs[0].textRuns.map(run => run.text).join('');
    expect(text).toContain('You may not:');
    expect(text).toContain('•draw cards from Reserve Deck;');
    expect(text).toContain('•search your Lost Pile.');
  });

  it('normalizes split hyphenated terms like re-circulate', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 20, y: 40, text: '1. Intro', fontSize: 18},
      {page: 1, x: 20, y: 30, text: 'You re -circulate cards and may re -shuffle.'},
      {page: 1, x: 20, y: 20, text: 'You re'},
      {page: 1, x: 70, y: 20, text: '-circulate again.'},
    ];

    const parsed = parseExtractedTextRuns(items, metadata);
    const text = parsed.sections[0].blocks
      .flatMap(block => block.textRuns)
      .map(run => run.text)
      .join(' ')
      .replace(/\s+/g, ' ')
      .trim();

    expect(text).toContain('re-circulate');
    expect(text).toContain('re-shuffle');
    expect(text).not.toContain('re -circulate');
  });

  it('adds missing spaces after contractions and possessives', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 20, y: 40, text: '1. Intro', fontSize: 18},
      {
        page: 1,
        x: 20,
        y: 30,
        text: "they'renot his, it'snot his Effect, and each player'sturn matters on opponent'sturn.",
      },
    ];

    const parsed = parseExtractedTextRuns(items, metadata);
    const text = parsed.sections[0].blocks
      .flatMap(block => block.textRuns)
      .map(run => run.text)
      .join(' ')
      .replace(/\s+/g, ' ')
      .trim();

    expect(text).toContain("they're not his");
    expect(text).toContain("it's not his Effect");
    expect(text).toContain("player's turn matters");
    expect(text).toContain("opponent's turn");
  });

  it('normalizes common joined extraction typos without dropping words', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 20, y: 40, text: '1. Intro', fontSize: 18},
      {
        page: 1,
        x: 20,
        y: 30,
        text: 'You donot reshuffle unless instructed to doso; then dothis and dothe check.',
      },
      {
        page: 1,
        x: 20,
        y: 20,
        text: 'You mus treveal cards to both pla yers before choosing.',
      },
      {
        page: 1,
        x: 20,
        y: 10,
        text: 'You may befor echoosing to treveal a selected card.',
      },
      {
        page: 1,
        x: 20,
        y: 5,
        text: 'Acti ons Exa mple: i twas tak esplace and tell mewhen to leave thei rown area.',
      },
      {
        page: 1,
        x: 20,
        y: 1,
        text: 'This should be toldotherwise and an dother case.',
      },
    ];

    const parsed = parseExtractedTextRuns(items, metadata);
    const text = parsed.sections[0].blocks
      .flatMap(block => block.textRuns)
      .map(run => run.text)
      .join(' ')
      .replace(/\s+/g, ' ')
      .trim();

    expect(text).toContain('do not reshuffle');
    expect(text).toContain('do so');
    expect(text).toContain('do this');
    expect(text).toContain('do the check');
    expect(text).toContain('must reveal cards to both players');
    expect(text).toContain('before choosing');
    expect(text).toContain('to reveal a selected card');
    expect(text).toContain('Actions Example: it was takes place');
    expect(text).toContain('tell me when to leave their own area');
    expect(text).toContain('told otherwise and and other case');
  });

  it('normalizes additional split-join artifacts in extracted words', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 20, y: 40, text: '1. Intro', fontSize: 18},
      {
        page: 1,
        x: 20,
        y: 30,
        text: "Astromechs function as nav computers a ndallow ships to jump. He do esn't wait; the response nev erhappens.",
      },
    ];

    const parsed = parseExtractedTextRuns(items, metadata);
    const text = parsed.sections[0].blocks
      .flatMap(block => block.textRuns)
      .map(run => run.text)
      .join(' ')
      .replace(/\s+/g, ' ')
      .trim();

    expect(text).toContain('and allow ships');
    expect(text).toContain("doesn't wait");
    expect(text).toContain('never happens');
  });

  it('creates sections from heading runs and assigns levels', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 20, y: 40, text: '1. General Rules', fontSize: 18},
      {page: 1, x: 20, y: 30, text: 'Paragraph under heading'},
      {page: 1, x: 20, y: 20, text: '1.1 Scope', fontSize: 14},
      {page: 1, x: 20, y: 10, text: 'Nested paragraph'},
    ];

    const parsed = parseExtractedTextRuns(items, metadata);

    expect(parsed.sections).toHaveLength(2);
    expect(parsed.sections[0].title).toBe('1. General Rules');
    expect(parsed.sections[0].level).toBe(1);
    expect(parsed.sections[0].blocks[1].textRuns[0].text).toBe(
      'Paragraph under heading',
    );

    expect(parsed.sections[1].title).toBe('1.1 Scope');
    expect(parsed.sections[1].level).toBe(2);
    expect(parsed.sections[1].blocks[1].textRuns[0].text).toBe('Nested paragraph');

    expect(parsed.toc.map(entry => entry.anchor)).toEqual([
      '1-general-rules',
      '1-1-scope',
    ]);
  });

  it('infers heading level from bold heading-like text when font size is moderate', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 20, y: 40, text: 'Chapter 3 Timing', fontSize: 11.5, isBold: true},
      {page: 1, x: 20, y: 30, text: 'Paragraph under heading'},
    ];

    const parsed = parseExtractedTextRuns(items, metadata);
    expect(parsed.sections[0].title).toBe('Chapter 3 Timing');
    expect(parsed.sections[0].level).toBe(2);
  });

  it('adds confidence metadata to paragraph blocks', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 20, y: 40, text: '1. Intro', fontSize: 18},
      {page: 1, x: 20, y: 30, text: 'unless a'},
      {page: 1, x: 20, y: 20, text: 'complete sentence with closure.'},
    ];

    const parsed = parseExtractedTextRuns(items, metadata);
    const paragraphs = parsed.sections[0].blocks.filter(block => block.type === 'paragraph');
    expect(paragraphs.length).toBeGreaterThan(0);
    expect(typeof paragraphs[0].confidenceScore).toBe('number');
    expect(Array.isArray(paragraphs[0].confidenceFlags)).toBe(true);
  });

  it('normalizes internal links into in-document anchors', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 20, y: 20, text: '2. Timing', fontSize: 18},
      {
        page: 1,
        x: 20,
        y: 10,
        text: 'See Actions and Responses.',
        internalHref: 'Actions and Responses',
      },
    ];

    const parsed = parseExtractedTextRuns(items, metadata);
    const paragraphRun = parsed.sections[0].blocks[1].textRuns[0];

    expect(paragraphRun.href).toBe('#actions-and-responses');
  });

  it('reconstructs line text from tokenized pdf runs', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 20, y: 40, text: '1. Sample', fontSize: 18},
      {page: 1, x: 20, y: 25, text: 'Action'},
      {page: 1, x: 58, y: 25, text: 'windows'},
      {page: 1, x: 117, y: 25, text: 'open'},
      {page: 1, x: 152, y: 25, text: 'after'},
      {page: 1, x: 186, y: 25, text: 'targets'},
      {page: 1, x: 230, y: 25, text: 'are'},
      {page: 1, x: 248, y: 25, text: 'chosen.'},
    ];

    const parsed = parseExtractedTextRuns(items, metadata);
    const paragraph = parsed.sections[0].blocks[1].textRuns.map(run => run.text).join('');
    expect(paragraph).toBe('Action windows open after targets are chosen.');
  });

  it('does not merge nearby lines with large indent changes into one paragraph', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 20, y: 40, text: '1. Sample', fontSize: 18},
      {page: 1, x: 20, y: 30, text: 'First line of paragraph'},
      {page: 1, x: 130, y: 24, text: 'Second line from different column'},
    ];

    const parsed = parseExtractedTextRuns(items, metadata);
    const blocks = parsed.sections[0].blocks.filter(block => block.type === 'paragraph');
    expect(blocks).toHaveLength(2);
  });

  it('drops toc dot-leader and linked page-number noise', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 20, y: 40, text: '1. Intro', fontSize: 18},
      {page: 1, x: 20, y: 30, text: '.....', internalHref: 'chapter-1'},
      {page: 1, x: 80, y: 30, text: '12', internalHref: 'chapter-1'},
      {page: 1, x: 20, y: 20, text: 'Readable content stays.'},
    ];

    const parsed = parseExtractedTextRuns(items, metadata);
    const paragraphText = parsed.sections[0].blocks[1].textRuns[0].text;
    expect(paragraphText).toBe('Readable content stays.');
  });

  it('drops linked TOC-style lines with long dot leaders and page numbers', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 20, y: 40, text: '1. Intro', fontSize: 18},
      {
        page: 1,
        x: 20,
        y: 30,
        text: 'Appendix E -Location Deployment..................... 181',
        internalHref: 'appendix-e-location-deployment',
      },
      {page: 1, x: 20, y: 20, text: 'Real section text.'},
    ];

    const parsed = parseExtractedTextRuns(items, metadata);
    const paragraphs = parsed.sections[0].blocks.filter(block => block.type === 'paragraph');
    expect(paragraphs).toHaveLength(1);
    expect(paragraphs[0].textRuns[0].text).toBe('Real section text.');
  });

  it('drops heading lines that contain only symbols/icons', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 20, y: 40, text: '1. Intro', fontSize: 18},
      {page: 1, x: 20, y: 30, text: '', fontSize: 18},
      {page: 1, x: 20, y: 20, text: 'Normal paragraph.'},
    ];

    const parsed = parseExtractedTextRuns(items, metadata);
    expect(parsed.sections).toHaveLength(1);
    expect(parsed.sections[0].title).toBe('1. Intro');
  });

  it('merges single-letter heading fragments into the previous heading', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 20, y: 40, text: 'Chapter 4 -Control Phase, Presence, & Force Drainin', fontSize: 18},
      {page: 1, x: 380, y: 40, text: 'g', fontSize: 18},
    ];

    const parsed = parseExtractedTextRuns(items, metadata);
    expect(parsed.sections).toHaveLength(1);
    expect(parsed.sections[0].title).toBe(
      'Chapter 4 -Control Phase, Presence, & Force Draining',
    );
  });

  it('flags likely row-wise column interleaving in audit metrics', () => {
    const items: ExtractedTextRun[] = [
      {page: 1, x: 20, y: 30, text: 'L1'},
      {page: 1, x: 220, y: 30, text: 'R1'},
      {page: 1, x: 20, y: 20, text: 'L2'},
      {page: 1, x: 220, y: 20, text: 'R2'},
      {page: 1, x: 20, y: 10, text: 'L3'},
      {page: 1, x: 220, y: 10, text: 'R3'},
    ];

    const audit = auditExtractedTextRuns(items);
    expect(audit[0].twoColumnDetected).toBe(true);
    expect(audit[0].columnTransitions).toBeGreaterThanOrEqual(1);
  });
});

describe('anchor helpers', () => {
  it('slugifies headings for stable ids', () => {
    expect(slugifyAnchor('  4.  Actions & Responses  ')).toBe(
      '4-actions-responses',
    );
  });

  it('deduplicates repeated headings with numeric suffixes', () => {
    const counts: Record<string, number> = {};
    const first = buildUniqueAnchor('Overview', counts);
    const second = buildUniqueAnchor('Overview', counts);
    const third = buildUniqueAnchor('Overview!', counts);

    expect(first).toBe('overview');
    expect(second).toBe('overview-2');
    expect(third).toBe('overview-3');
  });
});
